function load(key, fallback) {
  try { return JSON.parse(localStorage.getItem(key)) ?? fallback; }
  catch { return fallback; }
}
function save(key, val) {
  try { localStorage.setItem(key, JSON.stringify(val)); } catch {}
}
const mineOf = id => MINE[id] || {};
function setMine(id, patch) {
  MINE[id] = { ...mineOf(id), ...patch };
  // drop entries that carry no information, so exports stay clean
  const m = MINE[id];
  const empty = Object.values(m).every(v => v === '' || v === false || v == null);
  if (empty) delete MINE[id];
  save(MINE_KEY, MINE);
}

