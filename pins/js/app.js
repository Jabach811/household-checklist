function shortName(p) {
  let s = (p.name || '').replace(/^Disney\s+/i, '');
  // trim a redundant trailing "Pin"/"Pin Set", but never down to a stub
  const trimmed = s.replace(/\s*pin(\s+set)?\s*$/i, '');
  if (trimmed.length >= 12) s = trimmed;
  return s.slice(0, 42);
}

