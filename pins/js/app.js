function renderTable() {
  const cols = visibleCols();
  const head = $('#thead-row');
  head.textContent = '';
  for (const c of cols) {
    const th = el('th', { textContent: c.label });
    if (state.tableSort.key === c.key) {
      th.appendChild(el('span', { className: 'arrow', textContent: state.tableSort.dir > 0 ? ' ▲' : ' ▼' }));
    }
    th.onclick = () => {
      state.tableSort = state.tableSort.key === c.key
        ? { key: c.key, dir: -state.tableSort.dir }
        : { key: c.key, dir: 1 };
      PREFS.tableSort = state.tableSort; save(PREF_KEY, PREFS);
      renderTable();
    };
    head.appendChild(th);
  }

  const col = COLUMNS.find(c => c.key === state.tableSort.key) || COLUMNS[0];
  const rows = filtered().sort((a, b) => {
    const va = col.get(a), vb = col.get(b);
    const na = num(va), nb = num(vb);
    let r;
    if (na != null && nb != null) r = na - nb;
    else if (va == null || va === '') r = vb == null || vb === '' ? 0 : 1;   // blanks last
    else if (vb == null || vb === '') r = -1;
    else r = String(va).localeCompare(String(vb));
    return r * state.tableSort.dir || (a.name || '').localeCompare(b.name || '');
  });

  const tb = $('#tbody');
  tb.textContent = '';
  const frag = document.createDocumentFragment();
  for (const p of rows.slice(0, 600)) {
    const tr = el('tr');
    for (const c of cols) {
      const raw = c.get(p);
      const txt = c.fmt ? c.fmt(raw) : (raw == null || raw === '' ? '—' : String(raw));
      const td = el('td', { className: c.cls || '', textContent: txt });
      if (txt === '✓') td.className += ' tick';
      tr.appendChild(td);
    }
    tr.onclick = () => openDrawer(p);
    frag.appendChild(tr);
  }
  tb.appendChild(frag);
  $('#result-count').textContent =
    `${rows.length.toLocaleString()} of ${CATALOG.length.toLocaleString()} pins` +
    (rows.length > 600 ? ' · showing first 600' : '');
}

