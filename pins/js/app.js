/* ── filtering ──────────────────────────────────────────────────────────── */
function activeFilterCount() {
  let n = Object.values(state.filters).reduce((a, s) => a + s.size, 0);
  ['yearMin', 'yearMax', 'valMin', 'valMax'].forEach(k => { if (state[k] != null) n++; });
  return n;
}

function matches(p) {
  if (state.q) {
    const toks = state.q.toLowerCase().split(/\s+/).filter(Boolean);
    if (!toks.every(t => p._hay.includes(t))) return false;
  }
  for (const f of FACETS) {
    const sel = state.filters[f.key];
    if (!sel.size) continue;
    const v = f.get(p);
    const vals = Array.isArray(v) ? v : [v];
    if (!vals.some(x => sel.has(x))) return false;
  }
  const y = num(p.year);
  if (state.yearMin != null && (y == null || y < state.yearMin)) return false;
  if (state.yearMax != null && (y == null || y > state.yearMax)) return false;
  const v = marketValue(p);
  if (state.valMin != null && (v == null || v < state.valMin)) return false;
  if (state.valMax != null && (v == null || v > state.valMax)) return false;
  return true;
}

function sortPins(list, mode) {
  const by = {
    name:    (a, b) => (a.name || '').localeCompare(b.name || ''),
    year:    (a, b) => (num(a.year) ?? 9e9) - (num(b.year) ?? 9e9),
    value:   (a, b) => (marketValue(a) ?? -1) - (marketValue(b) ?? -1),
    rarity:  (a, b) => RARITY_ORDER.indexOf(a.rarity) - RARITY_ORDER.indexOf(b.rarity),
    series:  (a, b) => (a.series || 'zzz').localeCompare(b.series || 'zzz') ||
                       (a.series_position || '').localeCompare(b.series_position || ''),
  };
  const desc = mode.startsWith('-');
  const key = desc ? mode.slice(1) : mode;
  const cmp = by[key] || by.name;
  return list.slice().sort((a, b) => (desc ? -1 : 1) * cmp(a, b) || by.name(a, b));
}

