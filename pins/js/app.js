/* ── render: facets ─────────────────────────────────────────────────────── */
function renderFacets() {
  const base = filtered();
  const grid = $('#filters-grid');
  grid.textContent = '';
  for (const f of FACETS) {
    const counts = new Map();
    for (const p of base) {
      const v = f.get(p);
      for (const x of (Array.isArray(v) ? v : [v])) {
        if (x == null || x === '') continue;
        counts.set(x, (counts.get(x) || 0) + 1);
      }
    }
    // selected values must stay visible even at count 0
    for (const s of state.filters[f.key]) if (!counts.has(s)) counts.set(s, 0);
    if (!counts.size) continue;

    const order = f.key === 'rarity'
      ? [...counts.keys()].sort((a, b) => RARITY_ORDER.indexOf(a) - RARITY_ORDER.indexOf(b))
      : [...counts.keys()].sort((a, b) => counts.get(b) - counts.get(a) || String(a).localeCompare(String(b)));

    const list = el('div', { className: 'facet-list' });
    for (const v of order.slice(0, 60)) {
      const on = state.filters[f.key].has(v);
      const b = el('button', { className: 'chip', type: 'button' });
      b.setAttribute('aria-pressed', on);
      b.append(document.createTextNode(String(v) + ' '), el('span', { className: 'n', textContent: counts.get(v) }));
      b.onclick = () => {
        on ? state.filters[f.key].delete(v) : state.filters[f.key].add(v);
        state.page = 1; renderAll();
      };
      list.appendChild(b);
    }
    grid.appendChild(el('div', { className: 'facet' }, [el('h4', { textContent: f.label }), list]));
  }
  const n = activeFilterCount();
  const badge = $('#filter-count');
  badge.hidden = !n;
  badge.textContent = n;
}

/* ── render: cork board ─────────────────────────────────────────────────── */
function renderBoard() {
  const cork = $('#cork');
  cork.querySelectorAll('.pinned, .board-group').forEach(n => n.remove());

  let owned = CATALOG.filter(isOwned);
  if (state.boardFilter !== 'all') owned = owned.filter(p => p.franchise === state.boardFilter);
  if (state.q || activeFilterCount()) owned = owned.filter(matches);

  $('#cork-empty').hidden = owned.length > 0;

  const groups = new Map();
  for (const p of owned) {
    const g = p.franchise || 'Other';
    if (!groups.has(g)) groups.set(g, []);
    groups.get(g).push(p);
  }
  const order = ['Wizarding World', 'Disney', 'Pixar', 'Star Wars', 'Marvel'];
  const keys = [...groups.keys()].sort((a, b) => {
    const ia = order.indexOf(a), ib = order.indexOf(b);
    return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib) || a.localeCompare(b);
  });

  for (const k of keys) {
    if (keys.length > 1) cork.appendChild(el('div', { className: 'board-group', textContent: k }));
    for (const p of sortPins(groups.get(k), 'series')) cork.appendChild(pinnedNode(p));
  }

  /* Research identified pins physically on the board; offer to claim them in
     one go rather than making the owner tick 50-odd boxes by hand. */
  const unclaimed = CATALOG.filter(p => p.on_board && !isOwned(p));
  const banner = $('#claim-banner');
  banner.hidden = unclaimed.length === 0;
  $('#claim-count').textContent = unclaimed.length;

  /* Say plainly how much of the total is actually backed by price data —
     "$0 total" across 53 unpriced pins would read as a valuation, not a gap. */
  const withVal = owned.filter(p => marketValue(p) != null);
  const total = withVal.reduce((a, p) => a + marketValue(p), 0);
  const n = owned.length;
  let caption = '';
  if (n) {
    caption = `${n} pin${n === 1 ? '' : 's'} on the board · `;
    caption += withVal.length === 0
      ? 'none priced yet — open a pin and run a price check'
      : `${money(Math.round(total))} across the ${withVal.length} with a value on record` +
        (withVal.length < n ? ` · ${n - withVal.length} still unpriced` : '');
  }
  $('#board-caption').textContent = caption;
}

