function bars(sel, getter) {
  const counts = new Map();
  for (const p of CATALOG) {
    const v = getter(p);
    if (!v) continue;
    counts.set(v, (counts.get(v) || 0) + 1);
  }
  const rows = [...counts.entries()].sort((a, b) => b[1] - a[1]).slice(0, 12);
  const max = Math.max(1, ...rows.map(r => r[1]));
  const host = $(sel);
  host.textContent = '';
  rows.forEach(([k, n]) => {
    const fill = el('div', { className: 'bar-fill' });
    fill.style.width = (n / max * 100).toFixed(1) + '%';
    host.appendChild(el('div', { className: 'bar-row' }, [
      el('span', { className: 'lbl', textContent: k, title: k }),
      el('div', { className: 'bar-track' }, fill),
      el('span', { className: 'n', textContent: n }),
    ]));
  });
}

/* ── price link building ────────────────────────────────────────────────── */
function searchTerms(p) {
  const bits = [p.name];
  if (p.series && !new RegExp(escapeRe(p.series), 'i').test(p.name)) bits.push(p.series);
  const q = bits.join(' ')
    .replace(/[—–]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  const tight = /disney|wizarding|hogwarts|harry potter/i.test(q) ? q : q + ' Disney pin';
  return tight;
}
const escapeRe = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function priceLinks(p) {
  const q = encodeURIComponent(searchTerms(p));
  const img = p.image ? encodeURIComponent(absoluteUrl(p.image)) : null;
  return (SOURCES.sources || [])
    // reverse-image lookups are only meaningful once the pin has a picture
    .filter(s => !s.needs_image || img)
    .map(s => ({
      name: s.name,
      kind: s.kind,
      url: s.url_template.replace(/\{QUERY\}/g, q).replace(/\{IMAGE_URL\}/g, img || ''),
      primary: s.kind === 'sold-comps',
    }));
}
function absoluteUrl(u) {
  try { return new URL(u, location.href).href; } catch { return u; }
}

